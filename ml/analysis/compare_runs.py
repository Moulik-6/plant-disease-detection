#!/usr/bin/env python3
"""
Paired Cluster Bootstrap Model Comparison for Plant Disease Detection.

Compares model runs (and/or ensembles) using the per-image predictions CSV files
generated by ml/evaluate.py (predictions_<set>.csv).

Key features:
  - Aligns model predictions on image path
  - Resamples group_id clusters with replacement (cluster bootstrap)
  - Computes top-1 accuracy difference (B - A), 95% confidence interval,
    and empirical probability P(B > A)
  - Computes macro-F1 difference (B - A) over classes present, 95% CI, and P(B > A)
  - Reports discordant error matrix (A right/B wrong and B right/A wrong)
  - Prints a consolidated comparison table to stdout
  - Saves machine-readable JSON metrics to results/comparisons.json (or --out)

Usage:
  python ml/analysis/compare_runs.py --pair <runA> <runB> [--pair ...] [--set field_test] [--n-boot 5000] [--seed 42]
"""

import argparse
import csv
import json
import logging
import os
from pathlib import Path
import sys
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
from sklearn.metrics import f1_score

# Ensure repository root is in sys.path
_repo_root = Path(__file__).resolve().parents[2]
if str(_repo_root) not in sys.path:
    sys.path.insert(0, str(_repo_root))

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("compare_runs")


def resolve_predictions_file(run_path_str: str, set_name: str) -> Path:
    """
    Resolves the predictions_<set>.csv file from a run directory, baseline directory,
    summary directory, or direct file path.
    """
    p = Path(run_path_str)

    # 1. Direct path to a CSV file
    if p.is_file() and p.name.endswith(".csv"):
        if p.exists():
            return p.resolve()
        raise FileNotFoundError(f"Predictions CSV not found: {p}")

    # 2. Look inside run / summary directories
    candidates = [
        p / "eval" / f"predictions_{set_name}.csv",
        p / f"predictions_{set_name}.csv",
        p / "ensemble" / f"predictions_{set_name}.csv",
        p / "eval" / "ensemble" / f"predictions_{set_name}.csv",
        p / "ensemble" / "eval" / f"predictions_{set_name}.csv",
    ]

    for cand in candidates:
        if cand.exists():
            return cand.resolve()

    raise FileNotFoundError(
        f"Could not find predictions file for set '{set_name}' in '{run_path_str}'. "
        f"Checked: {[str(c) for c in candidates]}"
    )


def get_run_label(path: Path) -> str:
    """Extracts a concise, readable model label from a directory or file path."""
    p = path.resolve()
    if p.is_file():
        p = p.parent
    if p.name == "eval":
        p = p.parent
    if len(p.name) == 15 and p.name.replace("_", "").isdigit():
        return p.parent.name
    return p.name


def load_predictions_csv(csv_path: Path) -> Dict[str, Dict[str, Any]]:
    """
    Reads predictions_<set>.csv into a dictionary keyed by normalized image path.
    """
    records: Dict[str, Dict[str, Any]] = {}
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            raw_path = row.get("path", "").strip()
            if not raw_path:
                continue
            norm_path = raw_path.replace("\\", "/")

            raw_correct = row.get("correct", "").strip()
            if raw_correct in ("1", "True", "true"):
                correct_val = 1
            elif raw_correct in ("0", "False", "false"):
                correct_val = 0
            else:
                true_idx = int(row.get("true_idx", -1))
                pred_idx = int(row.get("pred_idx", -2))
                correct_val = int(true_idx >= 0 and true_idx == pred_idx)

            records[norm_path] = {
                "path": norm_path,
                "source": row.get("source", "").strip(),
                "true_label": row.get("true_label", "").strip(),
                "true_idx": int(row.get("true_idx", -1)),
                "pred_label": row.get("pred_label", "").strip(),
                "pred_idx": int(row.get("pred_idx", -1)),
                "confidence": float(row.get("confidence", 0.0)) if row.get("confidence") else 0.0,
                "correct": correct_val,
                "group_id": row.get("group_id", "").strip() or norm_path,
            }

    if not records:
        raise ValueError(f"No records found in predictions file: {csv_path}")

    return records


def run_paired_cluster_bootstrap(
    group_indices: np.ndarray,
    targets: np.ndarray,
    preds_a: np.ndarray,
    preds_b: np.ndarray,
    classes_present: np.ndarray,
    n_boot: int = 5000,
    seed: int = 42,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Executes paired cluster bootstrap resampling.
    Returns:
      (boot_diff_top1, boot_diff_f1) arrays of length n_boot.
    """
    n_samples = len(targets)
    k_clusters = int(np.max(group_indices)) + 1
    c_count = len(classes_present)

    # Pre-map present classes to local contiguous indices 0..C-1
    class_to_local = {cls_idx: i for i, cls_idx in enumerate(classes_present)}
    local_targets = np.array([class_to_local.get(t, -1) for t in targets], dtype=int)
    local_preds_a = np.array([class_to_local.get(p, -1) for p in preds_a], dtype=int)
    local_preds_b = np.array([class_to_local.get(p, -1) for p in preds_b], dtype=int)

    correct_a = (preds_a == targets)
    correct_b = (preds_b == targets)

    # 1. Cluster-level sums for Top-1 accuracy
    cluster_correct_a = np.bincount(group_indices, weights=correct_a.astype(np.float64), minlength=k_clusters)
    cluster_correct_b = np.bincount(group_indices, weights=correct_b.astype(np.float64), minlength=k_clusters)
    cluster_sizes = np.bincount(group_indices, minlength=k_clusters)

    # 2. Cluster-level statistics for Macro-F1: TP, target counts (support), predicted counts
    cluster_tp_a = np.zeros((k_clusters, c_count), dtype=np.float64)
    cluster_tp_b = np.zeros((k_clusters, c_count), dtype=np.float64)
    cluster_tgt = np.zeros((k_clusters, c_count), dtype=np.float64)
    cluster_pred_a = np.zeros((k_clusters, c_count), dtype=np.float64)
    cluster_pred_b = np.zeros((k_clusters, c_count), dtype=np.float64)

    for i in range(n_samples):
        g = group_indices[i]
        t = local_targets[i]
        pa = local_preds_a[i]
        pb = local_preds_b[i]

        if t >= 0:
            cluster_tgt[g, t] += 1.0
        if pa >= 0:
            cluster_pred_a[g, pa] += 1.0
            if pa == t:
                cluster_tp_a[g, t] += 1.0
        if pb >= 0:
            cluster_pred_b[g, pb] += 1.0
            if pb == t:
                cluster_tp_b[g, t] += 1.0

    rng = np.random.default_rng(seed)

    boot_diff_top1_list: List[np.ndarray] = []
    boot_diff_f1_list: List[np.ndarray] = []

    # Process in memory-efficient chunks
    chunk_size = 1000
    for start in range(0, n_boot, chunk_size):
        bsize = min(chunk_size, n_boot - start)
        sampled = rng.choice(k_clusters, size=(bsize, k_clusters), replace=True)

        # Top-1
        tot = cluster_sizes[sampled].sum(axis=1)
        corr_a = cluster_correct_a[sampled].sum(axis=1)
        corr_b = cluster_correct_b[sampled].sum(axis=1)
        top1_a = np.divide(corr_a, tot, out=np.zeros_like(corr_a), where=tot > 0)
        top1_b = np.divide(corr_b, tot, out=np.zeros_like(corr_b), where=tot > 0)
        boot_diff_top1_list.append(top1_b - top1_a)

        # Macro-F1
        tp_a = cluster_tp_a[sampled].sum(axis=1)
        tp_b = cluster_tp_b[sampled].sum(axis=1)
        tgt = cluster_tgt[sampled].sum(axis=1)
        pa = cluster_pred_a[sampled].sum(axis=1)
        pb = cluster_pred_b[sampled].sum(axis=1)

        den_a = tgt + pa
        den_b = tgt + pb

        with np.errstate(divide="ignore", invalid="ignore"):
            f1_a = np.where(den_a > 0, (2.0 * tp_a) / den_a, 0.0)
            f1_b = np.where(den_b > 0, (2.0 * tp_b) / den_b, 0.0)

        macro_a = np.mean(f1_a, axis=1) if c_count > 0 else np.zeros(bsize)
        macro_b = np.mean(f1_b, axis=1) if c_count > 0 else np.zeros(bsize)
        boot_diff_f1_list.append(macro_b - macro_a)

    boot_diff_top1 = np.concatenate(boot_diff_top1_list)
    boot_diff_f1 = np.concatenate(boot_diff_f1_list)

    return boot_diff_top1, boot_diff_f1


def compare_pair(
    run_a_path: str,
    run_b_path: str,
    set_name: str = "field_test",
    n_boot: int = 5000,
    seed: int = 42,
) -> Dict[str, Any]:
    """
    Performs full alignment and paired cluster bootstrap comparison between two runs.
    """
    file_a = resolve_predictions_file(run_a_path, set_name)
    file_b = resolve_predictions_file(run_b_path, set_name)

    records_a = load_predictions_csv(file_a)
    records_b = load_predictions_csv(file_b)

    common_paths = sorted([p for p in records_a if p in records_b])
    if not common_paths:
        raise ValueError(
            f"No overlapping image paths between:\n  Model A: {file_a}\n  Model B: {file_b}"
        )

    targets = np.array([records_a[p]["true_idx"] for p in common_paths], dtype=int)
    targets_b = np.array([records_b[p]["true_idx"] for p in common_paths], dtype=int)
    if not np.array_equal(targets, targets_b):
        raise ValueError("Ground-truth target mismatch between predictions files for common paths.")

    preds_a = np.array([records_a[p]["pred_idx"] for p in common_paths], dtype=int)
    preds_b = np.array([records_b[p]["pred_idx"] for p in common_paths], dtype=int)

    correct_a = (preds_a == targets)
    correct_b = (preds_b == targets)

    # Discordant counts
    n_a_right_b_wrong = int(np.sum(correct_a & ~correct_b))
    n_b_right_a_wrong = int(np.sum(~correct_a & correct_b))
    n_both_right = int(np.sum(correct_a & correct_b))
    n_both_wrong = int(np.sum(~correct_a & ~correct_b))

    # Point estimates
    top1_a = float(np.mean(correct_a))
    top1_b = float(np.mean(correct_b))
    diff_top1 = float(top1_b - top1_a)

    classes_present = np.unique(targets[targets >= 0])
    classes_present = np.sort(classes_present)

    macro_f1_a = float(f1_score(targets, preds_a, labels=classes_present, average="macro", zero_division=0))
    macro_f1_b = float(f1_score(targets, preds_b, labels=classes_present, average="macro", zero_division=0))
    diff_macro_f1 = float(macro_f1_b - macro_f1_a)

    # Clustered bootstrap setup
    raw_groups = [records_a[p].get("group_id", "") or p for p in common_paths]
    safe_groups = [g if (g and str(g).strip()) else f"indiv_{i}" for i, g in enumerate(raw_groups)]
    unique_groups, group_indices = np.unique(safe_groups, return_inverse=True)

    boot_diff_top1, boot_diff_f1 = run_paired_cluster_bootstrap(
        group_indices=group_indices,
        targets=targets,
        preds_a=preds_a,
        preds_b=preds_b,
        classes_present=classes_present,
        n_boot=n_boot,
        seed=seed,
    )

    ci_top1 = [float(np.percentile(boot_diff_top1, 2.5)), float(np.percentile(boot_diff_top1, 97.5))]
    p_pos_top1 = float(np.mean(boot_diff_top1 > 0))

    ci_f1 = [float(np.percentile(boot_diff_f1, 2.5)), float(np.percentile(boot_diff_f1, 97.5))]
    p_pos_f1 = float(np.mean(boot_diff_f1 > 0))

    return {
        "model_a": get_run_label(Path(run_a_path)),
        "model_b": get_run_label(Path(run_b_path)),
        "model_a_file": str(file_a),
        "model_b_file": str(file_b),
        "set": set_name,
        "num_samples": len(common_paths),
        "num_clusters": len(unique_groups),
        "classes_present_count": len(classes_present),
        "top1": {
            "model_a": top1_a,
            "model_b": top1_b,
            "diff": diff_top1,
            "ci_lower": ci_top1[0],
            "ci_upper": ci_top1[1],
            "ci_95": ci_top1,
            "p_positive": p_pos_top1,
        },
        "macro_f1": {
            "model_a": macro_f1_a,
            "model_b": macro_f1_b,
            "diff": diff_macro_f1,
            "ci_lower": ci_f1[0],
            "ci_upper": ci_f1[1],
            "ci_95": ci_f1,
            "p_positive": p_pos_f1,
        },
        "discordant": {
            "a_right_b_wrong": n_a_right_b_wrong,
            "b_right_a_wrong": n_b_right_a_wrong,
            "both_right": n_both_right,
            "both_wrong": n_both_wrong,
        },
    }


def print_comparison_table(results: List[Dict[str, Any]]) -> None:
    """Prints a clear, formatted comparison table to stdout."""
    headers = [
        "Comparison (Model B vs Model A)",
        "Top-1 (A)",
        "Top-1 (B)",
        "Top-1 Diff (95% CI)",
        "P(B > A)",
        "Macro-F1 (A)",
        "Macro-F1 (B)",
        "F1 Diff (95% CI)",
        "P(B > A)",
        "Discordant (A+/B-, B+/A-)",
    ]

    pair_labels = [f"{res['model_b']} vs {res['model_a']}" for res in results]
    first_col_w = max(32, max((len(lbl) for lbl in pair_labels), default=32) + 2)
    col_widths = [first_col_w, 10, 10, 28, 9, 13, 13, 28, 9, 26]

    def fmt_cell(val: str, width: int, align: str = "<") -> str:
        if align == ">":
            return f"{val:>{width}}"
        return f"{val:<{width}}"

    header_line = " | ".join(fmt_cell(h, col_widths[i], align="<" if i == 0 else ">") for i, h in enumerate(headers))
    sep_line = "-+-".join("-" * col_widths[i] for i in range(len(headers)))

    print("\n" + "=" * len(header_line))
    print(f" PAIRED CLUSTER BOOTSTRAP MODEL COMPARISON")
    print("=" * len(header_line))
    print(header_line)
    print(sep_line)

    for res in results:
        pair_label = f"{res['model_b']} vs {res['model_a']}"
        if len(pair_label) > col_widths[0]:
            pair_label = pair_label[: col_widths[0] - 3] + "..."

        t1 = res["top1"]
        f1 = res["macro_f1"]
        disc = res["discordant"]

        t1_diff_str = f"{t1['diff']:+.4f} [{t1['ci_lower']:+.4f}, {t1['ci_upper']:+.4f}]"
        f1_diff_str = f"{f1['diff']:+.4f} [{f1['ci_lower']:+.4f}, {f1['ci_upper']:+.4f}]"
        disc_str = f"({disc['a_right_b_wrong']}, {disc['b_right_a_wrong']})"

        row_vals = [
            pair_label,
            f"{t1['model_a']:.4f}",
            f"{t1['model_b']:.4f}",
            t1_diff_str,
            f"{t1['p_positive']:.4f}",
            f"{f1['model_a']:.4f}",
            f"{f1['model_b']:.4f}",
            f1_diff_str,
            f"{f1['p_positive']:.4f}",
            disc_str,
        ]

        row_line = " | ".join(fmt_cell(v, col_widths[i], align="<" if i == 0 else ">") for i, v in enumerate(row_vals))
        print(row_line)

    print(sep_line)
    print(f"Notes: Differences are computed as (Model B minus Model A).")
    print(f"       Discordant counts indicate (A correct & B wrong, B correct & A wrong).")
    print(f"       Confidence intervals and P(B > A) derived via group_id cluster bootstrap.\n")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Paired cluster bootstrap model comparison on predictions_<set>.csv."
    )
    parser.add_argument(
        "--pair",
        nargs=2,
        action="append",
        required=True,
        metavar=("RUN_A", "RUN_B"),
        help="Pair of run directories/checkpoints to compare (Model A and Model B). Repeatable.",
    )
    parser.add_argument(
        "--set",
        type=str,
        default="field_test",
        help="Evaluation set to compare (default: field_test).",
    )
    parser.add_argument(
        "--n-boot",
        type=int,
        default=5000,
        help="Number of cluster bootstrap resamples (default: 5000).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for cluster bootstrap (default: 42).",
    )
    parser.add_argument(
        "--out",
        type=str,
        default="results/comparisons.json",
        help="Destination path for output JSON (default: results/comparisons.json).",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    results = []
    for run_a, run_b in args.pair:
        logger.info("Comparing pair: '%s' vs '%s' (set: %s)", run_b, run_a, args.set)
        res = compare_pair(
            run_a_path=run_a,
            run_b_path=run_b,
            set_name=args.set,
            n_boot=args.n_boot,
            seed=args.seed,
        )
        results.append(res)

    print_comparison_table(results)

    # Save to JSON
    out_path = Path(args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    payload = {
        "set": args.set,
        "n_boot": args.n_boot,
        "seed": args.seed,
        "comparisons": results,
        "pairs": results,
    }

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    logger.info("Saved comparison results to: %s", out_path)


if __name__ == "__main__":
    main()
